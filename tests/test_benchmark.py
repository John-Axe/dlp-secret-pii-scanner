"""Tests for the precision/recall/F1 math used by benchmark/run_benchmark.py,
and an end-to-end check that the shipped corpus clears the documented gate.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "benchmark"))

from run_benchmark import (  # noqa: E402
    badge_color,
    evaluate,
    precision_recall_f1,
    render_table,
    write_badge,
)


def test_precision_recall_f1_perfect():
    precision, recall, f1 = precision_recall_f1(tp=10, fp=0, fn=0)
    assert precision == 1.0
    assert recall == 1.0
    assert f1 == 1.0


def test_precision_recall_f1_with_false_positives():
    precision, recall, f1 = precision_recall_f1(tp=9, fp=1, fn=0)
    assert precision == 0.9
    assert recall == 1.0
    assert round(f1, 4) == round(2 * 0.9 * 1.0 / (0.9 + 1.0), 4)


def test_precision_recall_f1_with_false_negatives():
    precision, recall, f1 = precision_recall_f1(tp=8, fp=0, fn=2)
    assert precision == 1.0
    assert recall == 0.8


def test_precision_recall_f1_no_signal_defaults_to_perfect():
    precision, recall, f1 = precision_recall_f1(tp=0, fp=0, fn=0)
    assert precision == 1.0
    assert recall == 1.0
    assert f1 == 1.0


def test_shipped_corpus_clears_documented_gate():
    results = evaluate()
    per_rule = results["per_rule"]
    total_tp = sum(c["tp"] for c in per_rule.values())
    total_fp = sum(c["fp"] for c in per_rule.values())
    total_fn = sum(c["fn"] for c in per_rule.values())
    precision, recall, _ = precision_recall_f1(total_tp, total_fp, total_fn)

    assert precision >= 0.85
    assert recall >= 0.85
    assert total_tp > 0


def test_committed_badge_matches_fresh_run(tmp_path):
    """Regression guard for a real drift this repo hit: the committed badge
    is only regenerated by CI's main-branch push job (never run yet, since
    nothing's been pushed) - CONTRIBUTING.md's "regenerate the badge when
    you touch the corpus" step is a manual instruction with nothing
    automated behind it, so README.md's table and .github/badges/
    benchmark.json silently went stale after a corpus change. This test is
    that missing automated check, running on every `pytest` invocation
    rather than only on a push to `main`.
    """
    results = evaluate()
    _, precision, recall, f1, *_ = render_table(results)

    fresh_path = tmp_path / "benchmark.json"
    write_badge(fresh_path, precision, recall, f1)
    fresh = json.loads(fresh_path.read_text())

    committed_path = REPO_ROOT / ".github" / "badges" / "benchmark.json"
    committed = json.loads(committed_path.read_text())

    assert fresh["message"] == committed["message"], (
        "committed .github/badges/benchmark.json is stale relative to the "
        "current corpus - regenerate it with `python benchmark/run_benchmark.py "
        "--badge-output .github/badges/benchmark.json` and commit the result "
        "(also update README.md's benchmark table by hand)"
    )
    assert fresh["color"] == committed["color"]


def test_badge_color_thresholds():
    assert badge_color(0.95) == "brightgreen"
    assert badge_color(0.9) == "brightgreen"
    assert badge_color(0.8) == "yellow"
    assert badge_color(0.5) == "red"


def _fake_results(**overrides):
    base = {
        "per_rule": {"aws_access_key_id": {"tp": 1, "fp": 0, "fn": 1}},
        "match_counts": {"aws_access_key_id": 3},
        "false_positives": [],
        "false_negatives": [("positives/missed.txt", "aws_access_key_id")],
    }
    base.update(overrides)
    return base


def test_render_table_includes_sample_size_column():
    table, *_ = render_table(_fake_results())
    header_line = table.splitlines()[0]
    assert "N" in header_line.split()
    # aws_access_key_id: tp=1, fn=1 -> sample size (N) is 2, not just tp=1.
    rule_line = next(line for line in table.splitlines() if line.startswith("aws_access_key_id"))
    assert rule_line.split()[1] == "2"


def test_render_table_returns_totals_matching_per_rule_sums():
    _, precision, recall, f1, total_tp, total_fp, total_fn = render_table(_fake_results())
    assert (total_tp, total_fp, total_fn) == (1, 0, 1)
    assert precision == 1.0
    assert recall == 0.5


def test_render_table_includes_match_level_diagnostics_section():
    table, *_ = render_table(_fake_results())
    assert "Match-level diagnostics" in table
    assert "aws_access_key_id: 3" in table


def test_render_table_omits_diagnostics_section_when_no_matches():
    table, *_ = render_table(_fake_results(match_counts={}))
    assert "Match-level diagnostics" not in table


def test_write_badge_produces_shields_io_endpoint_schema(tmp_path):
    badge_path = tmp_path / "badges" / "benchmark.json"

    write_badge(badge_path, precision=0.9444, recall=1.0, f1=0.9714)

    data = json.loads(badge_path.read_text())
    assert data["schemaVersion"] == 1
    assert "94%" in data["message"]
    assert "100%" in data["message"]
    assert data["color"] == "brightgreen"
